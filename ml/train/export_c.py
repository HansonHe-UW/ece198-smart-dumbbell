"""Write model.json as a C header for firmware/classifier/ (plain C++ inference, no TFLite)."""
from __future__ import annotations

import json
from pathlib import Path


def _arr(name, values, dims):
    flat = [v for row in values for v in row] if isinstance(values[0], list) else values
    body = ",\n  ".join(", ".join(f"{v:.6f}f" for v in flat[i:i + 8]) for i in range(0, len(flat), 8))
    return f"static const float {name}{dims} = {{\n  {body}\n}};\n"


def write_header(model: dict, path: Path) -> None:
    layers = model["layers"]
    n_in = len(model["feature_names"])
    lines = ["// Generated by ml/train/train.py. Do not edit; retrain instead.",
             f"// model: {model['model']}, synthetic: {model['synthetic']}, windows: {model['n_windows']}, "
             f"pooled LOPO macro-F1: {model['pooled_macro_f1']:.3f}",
             "#pragma once", "",
             f"#define CLF_FS {model['fs']}", f"#define CLF_WINDOW {model['window']}", f"#define CLF_HOP {model['hop']}",
             f"#define CLF_N_FEATURES {n_in}", f"#define CLF_N_CLASSES {len(model['classes'])}",
             f"#define CLF_N_LAYERS {len(layers)}", ""]
    lines.append("static const char* const CLF_CLASSES[CLF_N_CLASSES] = {" + ", ".join(f'"{c}"' for c in model["classes"]) + "};")
    lines.append(_arr("CLF_SCALER_MEAN", model["scaler_mean"], f"[{n_in}]"))
    lines.append(_arr("CLF_SCALER_SCALE", model["scaler_scale"], f"[{n_in}]"))
    sizes = [n_in] + [len(l["b"]) for l in layers]
    lines.append("static const int CLF_LAYER_SIZES[CLF_N_LAYERS + 1] = {" + ", ".join(map(str, sizes)) + "};")
    for i, l in enumerate(layers):
        lines.append(_arr(f"CLF_W{i}", l["W"], f"[{sizes[i]} * {sizes[i+1]}]"))   # row-major [in][out]
        lines.append(_arr(f"CLF_B{i}", l["b"], f"[{sizes[i+1]}]"))
    lines.append("static const float* const CLF_W[CLF_N_LAYERS] = {" + ", ".join(f"CLF_W{i}" for i in range(len(layers))) + "};")
    lines.append("static const float* const CLF_B[CLF_N_LAYERS] = {" + ", ".join(f"CLF_B{i}" for i in range(len(layers))) + "};")
    path.write_text("\n".join(lines) + "\n")


def write_selftest_header(window, feats, probs, source: str, path: Path) -> None:
    """One raw window plus the Python features and probabilities, for firmware/classifier self-test."""
    rows = ",\n  ".join("{" + ", ".join(f"{v:.3f}f" for v in row) + "}" for row in window.tolist())
    lines = ["// Generated by ml/train/train.py from " + source + ". Do not edit.", "#pragma once", "",
             f"#define SELFTEST_WINDOW {len(window)}",
             f"static const float SELFTEST_RAW[SELFTEST_WINDOW][6] = {{\n  {rows}\n}};",
             _arr("SELFTEST_FEATURES", [float(v) for v in feats], f"[{len(feats)}]"),
             _arr("SELFTEST_PROBS", [float(v) for v in probs], f"[{len(probs)}]")]
    path.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    import sys
    m = json.loads(Path(sys.argv[1]).read_text())
    write_header(m, Path(sys.argv[2]))
